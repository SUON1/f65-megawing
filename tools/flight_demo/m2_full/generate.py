"""Fixed development composition contract; rejects drift before writes."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EXPECTED = 'ff6e66962f9c58ff92d3186586287e9a96f12a1393b43ac4c8bc80c852545848'


def generate(root=ROOT, destination=None):
    source = (root / 'interfaces/m2_full.json').read_bytes()
    if hashlib.sha256(source).hexdigest() != EXPECTED:
        raise ValueError('Unreviewed M2 full-composition contract')
    data = json.loads(source)
    header = ['// Generated by m2_full/generate.py. Do not edit.', '#pragma once',
              '#include "m2_pr1.h"', '#include "m1_development.h"']
    for key, value in data.items():
        if isinstance(value, int):
            header.append(f'#define M2_FULL_{key.upper()} {value}UL')
    for name, fields in data['records'].items():
        header.append('typedef struct\n{')
        for field, kind in fields:
            base, _, suffix = kind.partition('[')
            header.append(f'    {base} {field}' + ('[' + suffix if suffix else '') + ';')
        header.append('} ' + name + ';')
    ledger = {'identity':data['identity'], 'source_sha256':EXPECTED,
              'resident':[data['resident_start'],data['resident_end']],
              'hardware_stack':[256,512], 'base_page':[512,768],
              'software_stack':[data['software_stack_start'],data['software_stack_end']],
              'displays':[{'start':base,'bytes':data['store_bytes'],'owner':'Graphics'} for base in data['stores']],
              'color':{'start':data['color_base'],'bytes':data['screen_bytes'],'immutable_after_init':True},
              'reserve_allocation':0,
              'objects':{'Core/Input/Presentation':'linked existing owner objects',
                         'Graphics':'two bundles, prepared context, snapshot, cursor, line, tile[64], text[320], counters',
                         'Diagnostics':'requested camera and prior semantic command bits',
                         'font':'owned 8x8 bitmap constants, charged in rodata',
                         'Platform':'existing lifecycle/copy objects plus static compiler scratch'},
              'alias_policy':'no overlapping object lifetimes or reused owner bands',
              'status':'actual sizes required from complete link; no execution admission'}
    destination = destination or root
    for path, value in [('interfaces/generated/m2_full.h','\n'.join(header)+'\n'),
                        ('memory/m2-full-ledger.json',json.dumps(ledger,indent=2)+'\n')]:
        output = destination/path
        output.parent.mkdir(parents=True,exist_ok=True)
        output.write_text(value)
    return data


if __name__ == '__main__':
    generate()
