"""Generate the founder-approved private development residency extension only."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CONTRACT = "interfaces/m2_extended_resident.json"
OUTPUTS = ("interfaces/generated/m2_extended_resident.h",
           "memory/m2-extended-resident-ledger.json",
           "src/platform/m2_rebuild/extended_resident.ld")


def load(root=ROOT):
    data = json.loads((root / CONTRACT).read_text())
    assert data["identity"] == "65AERO-M2-EXTRES-1"
    assert data["production_resident"] == [0x2001, 0x8000]
    assert data["development_resident"] == [0x2001, 0x9000]
    assert data["extension"] == [0x8000, 0x9000]
    assert data["forbidden_covering_map_block"] == [0x8000, 0xa000]
    assert data["map_block_bytes"] == 8192
    assert data["hardware_stack"] == [0x100, 0x200]
    assert data["base_page"] == [0x200, 0x300]
    assert data["software_stack"] == [0xc000, 0xd000]
    assert data["protected_reserve"] == [0x58000, 0x60000]
    assert data["reserve_used"] == 0 and not data["banking"] and not data["dma"]
    assert (data["tick_hz"], data["stages"], data["normal_world_minimum_hz"]) == (100, 21, 20)
    assert not data["runtime_enablement"] and data["target_budgets"] == [0] * 8
    base = json.loads((root / "interfaces/m2_rebuild.json").read_text())
    assert base["memory"]["resident"] == data["production_resident"]
    assert base["memory"]["reserve_used"] == 0
    return data


def generate(root=ROOT, destination=None):
    data = load(root)
    digest = hashlib.sha256((root / CONTRACT).read_bytes()).hexdigest()
    header = ("// Generated by m2_rebuild/residency.py; do not edit.\n"
              "#pragma once\n"
              '#define M2RE_IDENTITY "' + data["identity"] + '"\n'
              "#define M2RE_RESIDENT_START 8193UL\n"
              "#define M2RE_RESIDENT_END_EXCLUSIVE 36864UL\n"
              "#define M2RE_PRODUCTION_END_EXCLUSIVE 32768UL\n"
              "#define M2RE_FORBIDDEN_MAP_END_EXCLUSIVE 40960UL\n")
    ledger = {"identity": data["identity"], "contract_sha256": digest,
              "status": "development-only allocation; runtime admission pending",
              "owner": data["physical_owner"],
              "resident": data["development_resident"],
              "production_resident_unchanged": data["production_resident"],
              "forbidden_covering_map_block": data["forbidden_covering_map_block"],
              "staging_policy": data["staging_policy"], "lifetime": "initial PRG load through reset",
              "unchanged_owner_ledger": "memory/m2-rebuild-ledger.json",
              "hardware_stack": data["hardware_stack"], "base_page": data["base_page"],
              "software_stack": data["software_stack"], "reserve_used": 0,
              "other_owner_allocations_changed": False, "banking": False,
              "execution_admitted": False}
    linker = """/* Generated by m2_rebuild/residency.py; development profile only. */
INCLUDE src/platform/m2_rebuild/startup.ld
__m2re_noinit_start = ADDR(.noinit);
__m2re_noinit_end = ADDR(.noinit) + SIZEOF(.noinit);
ASSERT(ADDR(.basic_header) == 0x2001, "extended profile PRG origin changed")
ASSERT(ADDR(.text) + SIZEOF(.text) <= 0x9000, "extended profile text exceeds $9000")
ASSERT(ADDR(.rodata) + SIZEOF(.rodata) <= 0x9000, "extended profile constants exceed $9000")
ASSERT(ADDR(.data) + SIZEOF(.data) <= 0x9000, "extended profile data exceeds $9000")
ASSERT(ADDR(.bss) + SIZEOF(.bss) <= 0x9000, "extended profile BSS exceeds $9000")
ASSERT(__m2re_noinit_end <= 0x9000, "extended profile scratch exceeds $9000")
ASSERT(__stack == 0xd000, "extended profile software stack changed")
ASSERT(m2rb_startup < 0x8000, "normalization entry must precede extension")
ASSERT(m2re_startup_done < 0x8000, "visibility checks must precede extension")
"""
    contents = [header, json.dumps(ledger, indent=2) + "\n", linker]
    for name, content in zip(OUTPUTS, contents):
        path = (destination or root) / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return data


if __name__ == "__main__":
    generate()
