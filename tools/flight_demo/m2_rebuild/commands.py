"""One source for the private exact numerical command program (no public ABI)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DESTINATION = ROOT / "src/graphics/m2_commands.inc"

# High bits describe which operands are wide addresses: destination/first/last.
OPS = {"COPY": 0x60, "ADD": 0xE1, "SUB": 0xE2, "NEG": 0x63,
       "DOUBLE": 0x24, "SINE": 0x25, "DELTA": 0x26,
       "MUL_SET": 0xE8, "MUL_ADD": 0xE9, "MUL_SUB": 0xEA,
       "PRODUCT": 0xCB, "MUL_INTEGER_ADD": 0xEC,
       "DIV_SET": 0xAD, "DIV_ADD": 0xEE,
       "NEXT": 15, "JUMP": 16, "CLIP": 17, "RETURN": 18,
       "SCREEN": 19, "HORIZON_INIT": 20, "HORIZON_STEP": 21,
       "DONE": 22, "NEGATIVE": 0x57, "POSITIVE": 0x58}
CONSTANTS = ["0", "(int64_t)M2_NEAR_FT * M2_CLIP_SCALE",
             "(int64_t)M2_FAR_FT * M2_CLIP_SCALE",
             "M2_FOCAL * M2_SCREEN_SCALE", "320", "319", "-319", "-127"]


def program():
    code, labels = [], {}

    def label(name):
        assert name not in labels
        labels[name] = len(code)

    def emit(op, destination=0, first=0, last=0):
        code.append((op, destination, first, last))

    label("PREPARE")
    for i in range(6):
        emit("SINE", i, i // 2, 90 if i % 2 else 0)
    emit("NEG", 15, 2)
    products = [(4,2,6,0),(5,2,7,0),(3,1,0,1),(3,0,1,1),
                (6,1,3,1),(5,0,3,3),(6,0,4,1),(5,1,4,2),
                (4,3,5,1),(7,1,6,1),(4,0,6,2),
                (7,0,7,1),(4,1,7,3),(5,3,8,1)]
    for first, last, destination, operation in products:
        emit("MUL_SET" if operation < 2 else ("MUL_ADD" if operation == 2 else "MUL_SUB"),
             destination if operation == 0 else destination + 13, first, last)
    emit("DONE", 1)
    label("PREPARE_END")

    label("PROJECT")
    label("ROW")
    emit("COPY", 10, 128)
    label("AXIS")
    emit("DELTA", 11)
    emit("MUL_ADD", 10, 11, 25)  # matrix[row*3+axis]
    emit("NEXT", 2, 3, "AXIS")
    emit("COPY", 26, 10)  # point[end*3+row]
    emit("NEXT", 1, 3, "ROW")
    emit("NEXT", 0, 2, "ROW")
    for plane in range(6):
        for end in range(2):
            point, distance = end * 3, 6 + end
            if plane == 0:
                emit("SUB", distance, point, 129)
            elif plane == 1:
                emit("SUB", distance, 130, point)
            elif plane < 4:
                emit("ADD" if plane == 2 else "SUB", distance, point, point + 1)
            else:
                emit("COPY", distance, point)
                emit("DOUBLE", distance)
                emit("COPY", 11, point + 2)
                emit("DOUBLE", 11)
                emit("DOUBLE", 11)
                emit("ADD", 11, 11, point + 2)
                emit("ADD" if plane == 4 else "SUB", distance, distance, 11)
        emit("CLIP", 0, "INTERPOLATE")
    label("SCREEN")
    emit("PRODUCT", 0, 29, 131)  # component[end*3+axis+1] * focalQ16
    emit("DIV_SET", 11, 0, 30)  # positive forward[end*3]
    emit("SCREEN")
    emit("NEXT", 2, 2, "SCREEN")
    emit("NEXT", 0, 2, "SCREEN")
    emit("DONE", 2)
    label("INTERPOLATE")
    emit("SUB", 11, 27, 28)  # outside[axis] - inside[axis]
    emit("PRODUCT", 0, 11, 8)
    emit("DIV_ADD", 27, 28, 9)
    emit("NEXT", 2, 3, "INTERPOLATE")
    emit("RETURN")
    label("PROJECT_END")

    label("HORIZON")
    emit("HORIZON_INIT")
    emit("COPY", 23, 18)  # dx=2*m5
    emit("DOUBLE", 23)
    emit("COPY", 24, 21)  # dy=2*m8; must stay positive
    emit("DOUBLE", 24)
    emit("POSITIVE", 0, 24)
    emit("COPY", 22, 128)
    emit("MUL_INTEGER_ADD", 22, 15, 132)
    emit("NEGATIVE", 0, 18, "HORIZON_NEGATIVE")
    emit("MUL_INTEGER_ADD", 22, 18, 133)
    emit("JUMP", 0, "HORIZON_LAST")
    label("HORIZON_NEGATIVE")
    emit("MUL_INTEGER_ADD", 22, 18, 134)
    label("HORIZON_LAST")
    emit("MUL_INTEGER_ADD", 22, 21, 135)
    emit("HORIZON_STEP")
    emit("DONE", 3)
    label("HORIZON_END")
    assert len(code) < 256
    resolved = []
    for op, a, b, c in code:
        values = [labels[x] if isinstance(x, str) else x for x in (a,b,c)]
        assert all(0 <= x <= 255 for x in values)
        resolved.append((OPS[op], *values))
    return code, resolved, labels


def generate(destination=DESTINATION):
    symbolic, code, labels = program()
    lines = ["// Generated by commands.py; private numerical control, not public authority.",
             "enum {" + ", ".join(f"M2V_{name}={value}" for name,value in OPS.items()) + "};",
             "enum {" + ", ".join(f"M2P_{name}={value}" for name,value in labels.items()) + "};",
             "static const int64_t m2_command_constants[] = {" + ", ".join(CONSTANTS) + "};",
             "#ifdef M2_COMMAND_TEST_DATA",
             "static uint8_t m2_commands[][4] = {",
             "#else", "static const uint8_t m2_commands[][4] = {", "#endif"]
    for symbolic_row, row in zip(symbolic, code):
        lines.append("    {" + ",".join(map(str,row)) + "}, // " + symbolic_row[0])
    lines += ["};", ""]
    data = "\n".join(lines)
    destination.write_text(data)
    return {"instructions": len(code), "program_bytes": len(code)*4,
            "constant_bytes": len(CONSTANTS)*8, "labels": labels}


if __name__ == "__main__":
    print(generate())
