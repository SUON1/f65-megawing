"""Private minimum reimplementation contracts; no public layout writes."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EXPECTED = "9567374c9b08c1f24e9d58caca081885841dea42ae08c04e8b898e1dd42c7efb"


def generate(root=ROOT, destination=None):
    raw = (root / "interfaces/m2_rebuild.json").read_bytes()
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        raise ValueError("Unreviewed minimum-rebuild contract")
    data = json.loads(raw)
    if data["selection"] != [0, 1, 2, 3, 4, 5, 7, 11, 15]:
        raise ValueError("minimum selection changed")
    if data["target_budgets"] != [0] * 8 or data["runtime_enablement"]:
        raise ValueError("runtime admission is not authorized")
    header = ["// Generated by m2_rebuild/generate.py; do not edit.",
              "#pragma once", '#include "m2_pr1.h"', '#include "m1_development.h"',
              '#define M2RB_IDENTITY "' + data["identity"] + '"']
    for name in ["composition_revision", "width", "height", "world_height",
                 "columns", "text_rows", "tile_bytes", "tile_offset",
                 "blank_offset", "store_bytes", "color_base", "color_bytes"]:
        header.append("#define M2RB_" + name.upper() + " " + str(data[name]) + "UL")
    header += ["#define M2RB_SEGMENTS 9u",
               "static const uint8_t m2rb_segment_ids[M2RB_SEGMENTS] = {"
               + ", ".join(str(n) + "u" for n in data["selection"]) + "};"]
    for name, value in data["colors"].items():
        header.append("#define M2RB_" + name + " " + str(value) + "u")
    for name, fields in data["records"].items():
        header.append("typedef struct\n{")
        header += ["    " + kind + " " + field + ";" for field, kind in fields]
        header.append("} " + name + ";")
    ledger = {
        "identity": data["identity"], "source_sha256": EXPECTED,
        "status": "source baseline only; actual target fit/stack/service required",
        "ranges": data["memory"],
        "displays": [{"owner": "Graphics", "start": p, "bytes": data["store_bytes"]}
                     for p in data["stores"]],
        "color": {"owner": "Graphics/Platform", "start": data["color_base"],
                  "bytes": data["color_bytes"], "immutable_after_init": True},
        "objects": {
            "Graphics": "prepared camera/transform; two generated bundles; nine lines/visibility flags; snapshot; raster cursor; tile[64]; text[40]; counters",
            "Diagnostics": "requested camera and revision",
            "Input": "semantic prior key mask",
            "Core/Presentation": "unchanged integrated owner objects",
            "Platform": "existing lifecycle and new checked copy/mode adapter",
            "compiler": "actual static scratch and both stack domains from target evidence"},
        "lifetime_aliasing": "none", "reserve_allocation": 0,
        "banking": False, "dma_lists": [],
        "execution_admitted": False
    }
    target = destination or root
    for name, text in {
        "interfaces/generated/m2_rebuild_profile.h": "\n".join(header) + "\n",
        "memory/m2-rebuild-ledger.json": json.dumps(ledger, indent=2) + "\n"
    }.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return data


if __name__ == "__main__":
    generate()
