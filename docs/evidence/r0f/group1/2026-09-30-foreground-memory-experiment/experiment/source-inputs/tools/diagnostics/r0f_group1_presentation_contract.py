"""Generate diagnostic parameters, never production graphics limits/layouts."""
import json
from pathlib import Path

from r0f_group1_contract import validate_fields

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "interfaces/r0f_group1_presentation_contract.json"
HEADER = ROOT / "interfaces/generated/r0f_group1_presentation.h"


def validate(wire):
    c = wire["constants"]
    fields = {"VIEWS", "BUFFERS", "TIERS", "ANCHORS", "ANCHOR_PRIORITIES",
              "OCCLUSION_COLUMNS", "LOD_ENTER_PIXELS", "LOD_EXIT_PIXELS",
              "VIEW_TICK_SHIFT", "SCENE_CANDIDATES", "ANCHOR_BYTES",
              "COLUMN_BYTES", "SCENE_COPIES", "SCENE_BYTES"}
    if set(c) != fields or any(type(value) is not int for value in c.values()):
        raise ValueError("private fixture constants must be exact integer fields")
    if (wire["status"] != "PRIVATE_DIAGNOSTIC_NOT_PRODUCTION_ABI_OR_MEASURED_LIMITS"
            or c["VIEWS"] != 2 or c["BUFFERS"] != 2 or c["TIERS"] != 2
            or c["ANCHOR_PRIORITIES"] != 4 or not 1 <= c["ANCHORS"] <= 255
            or not 1 <= c["OCCLUSION_COLUMNS"] <= 8
            or not 0 <= c["LOD_EXIT_PIXELS"] < c["LOD_ENTER_PIXELS"] <= 65535
            or c["VIEW_TICK_SHIFT"] != 7 or c["SCENE_CANDIDATES"] != 6
            or c["ANCHORS"] != 4 or c["OCCLUSION_COLUMNS"] != 4
            or c["ANCHOR_BYTES"] != 7 or c["COLUMN_BYTES"] != 4
            or c["SCENE_COPIES"] != 9
            or c["SCENE_BYTES"] != 65):
        raise ValueError("unsupported private presentation fixture geometry")
    validate_fields(wire["sceneOffsets"], c["SCENE_BYTES"], {
        "GENERATION": 2, "SOURCE_TICK": 2, "HORIZON": 2,
        "ANCHORS": c["ANCHORS"] * c["ANCHOR_BYTES"],
        "COLUMNS": c["OCCLUSION_COLUMNS"] * c["COLUMN_BYTES"],
        "VISIBLE_BOTTOMS": c["OCCLUSION_COLUMNS"] * 2,
    }, 1)
    return c


def generate():
    wire = json.loads(PATH.read_text())
    c = validate(wire)
    lines = ["/* Generated by r0f_group1_presentation_contract.py. */",
             "/* Diagnostic parameters only; no production ABI/limit selection. */",
             "#ifndef R0FG1_PRESENTATION_GENERATED_H",
             "#define R0FG1_PRESENTATION_GENERATED_H"]
    lines += [f"#define R0FG1P_{name} {value}u" for name, value in c.items()]
    lines += [f"#define R0FG1P_S_{name} {value}u"
              for name, value in wire["sceneOffsets"].items()]
    lines += [f"#define R0FG1P_OCCLUSION_MASK {(1 << c['OCCLUSION_COLUMNS']) - 1}u",
              "#endif", ""]
    HEADER.write_text("\n".join(lines))
    return wire


if __name__ == "__main__":
    generate()
